import { createAccessPolicy } from '../src/policy';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { writeFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { createAuth } from '../src/auth';
const database = new DatabaseSync(':memory:');
const auth = createAuth(database, randomBytes(32).toString('hex'), 'http://localhost:8787', async () => {}, createAccessPolicy('admin@example.test'));
const migration = await getMigrations(auth.options);
await writeFile('migrations/0001_auth.sql', await migration.compileMigrations());
database.close();
console.log('Generated initial SQLite/D1 schema from the pinned auth configuration.');
